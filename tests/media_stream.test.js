'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const net=require('node:net');
const {spawn}=require('node:child_process');
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const freePort=()=>new Promise((resolve,reject)=>{const s=net.createServer();s.once('error',reject);s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
test('authenticated SSE updates and revision-safe media upload with range playback',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'eventflow-media-'));
 const port=await freePort();
 const child=spawn(process.execPath,['server.js'],{cwd:path.join(__dirname,'..'),env:{...process.env,EVENTFLOW_DATA:dir,EVENTFLOW_ADMIN_PASSWORD:'testPassword123',HOST:'127.0.0.1',PORT:String(port)},stdio:'pipe'});
 const ctrl=new AbortController();
 t.after(()=>{ctrl.abort();child.kill();fs.rmSync(dir,{recursive:true,force:true});});
 const root='http://127.0.0.1:'+port;
 let ready=false;for(let i=0;i<80;i++){try{if((await fetch(root+'/api/health')).ok){ready=true;break;}}catch{}await wait(75);}
 assert.equal(ready,true);
 const request=async(route,method,body,cookie)=>{
  const headers={};if(cookie)headers.Cookie=cookie;if(body!==undefined)headers['Content-Type']='application/json';
  const r=await fetch(root+route,{method,headers,body:body===undefined?undefined:JSON.stringify(body)});
  return {code:r.status,json:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};
 };
 const login=await request('/api/login','POST',{username:'admin',password:'testPassword123'});
 assert.equal(login.code,200);const cookie=login.cookie;
 const created=await request('/api/events','POST',{title:'Streaming Test',date:'2026-11-12',start:'09:00'},cookie);
 const id=created.json.event.id;
 const lease=await request('/api/events/'+id+'/lease','POST',{},cookie);
 assert.equal(lease.code,200);
 const sse=await fetch(root+'/api/stream',{headers:{Cookie:cookie},signal:ctrl.signal});
 assert.equal(sse.status,200);
 assert.match(sse.headers.get('content-type'),/text\/event-stream/);
 const reader=sse.body.getReader();
 const first=await reader.read();
 assert.match(new TextDecoder().decode(first.value),/connected/);
 const p=await request('/api/events/'+id+'/programs','POST',{revision:lease.json.event.revision,title:'Video Test',type:'video',duration:70,gap:10,sourceType:'none'},cookie);
 assert.equal(p.code,201);
 const next=await Promise.race([reader.read(),wait(3000).then(()=>null)]);
 assert.ok(next,'SSE event received after creating a program');
 assert.match(new TextDecoder().decode(next.value),/eventId/);
 const pid=p.json.programs[0].id;
 const data=Buffer.from('eventflow-test-video-content');
 const uploadUrl='/api/events/'+id+'/media?program='+pid+'&filename=sample.mp4&revision='+p.json.event.revision;
 const wrong=await fetch(root+uploadUrl.replace('revision='+p.json.event.revision,'revision=0'),{method:'POST',headers:{Cookie:cookie},body:data});
 assert.equal(wrong.status,409);
 const uploaded=await fetch(root+uploadUrl,{method:'POST',headers:{Cookie:cookie},body:data});
 assert.equal(uploaded.status,200);
 const uploadBody=await uploaded.json();
 assert.equal(uploadBody.program.sourceType,'file');
 assert.match(uploadBody.program.source,/\.mp4$/);
 const media='/media/'+uploadBody.program.source;
 const ranged=await fetch(root+media,{headers:{Cookie:cookie,Range:'bytes=0-8'}});
 assert.equal(ranged.status,206);
 assert.equal(ranged.headers.get('content-range'),'bytes 0-8/'+data.length);
 assert.equal(Buffer.from(await ranged.arrayBuffer()).toString(),'eventflow');
 const anonymous=await fetch(root+media);
 assert.equal(anonymous.status,401);
 const disk=JSON.parse(fs.readFileSync(path.join(dir,'data.json'),'utf8'));
 assert.equal(disk.programs[0].sourceType,'file');
 assert.ok(fs.existsSync(path.join(dir,'media',disk.programs[0].source)));
});
