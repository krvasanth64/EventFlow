'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const net=require('node:net');
const {spawn}=require('node:child_process');
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
function port(){return new Promise((resolve,reject)=>{const server=net.createServer();server.on('error',reject);server.listen(0,'127.0.0.1',()=>{const p=server.address().port;server.close(()=>resolve(p));});});}
test('live start pause resume stop and finish plus independent award planning',async t=>{
 const folder=fs.mkdtempSync(path.join(os.tmpdir(),'eventflow-onair-'));
 const p=await port();
 const host=spawn(process.execPath,['server.js'],{cwd:path.join(__dirname,'..'),env:{...process.env,EVENTFLOW_DATA:folder,EVENTFLOW_ADMIN_PASSWORD:'testPassword123',HOST:'127.0.0.1',PORT:String(p)},stdio:'pipe'});
 t.after(()=>{host.kill();fs.rmSync(folder,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+p;let connected=false;
 for(let i=0;i<80;i++){try{if((await fetch(base+'/api/health')).ok){connected=true;break;}}catch{}await wait(70);}
 assert.ok(connected);
 const call=async(route,method='GET',data,token)=>{
  const headers={};if(token)headers.Cookie=token;if(data!==undefined)headers['Content-Type']='application/json';
  const r=await fetch(base+route,{method,headers,body:data===undefined?undefined:JSON.stringify(data)});
  return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};
 };
 const login=await call('/api/login','POST',{username:'admin',password:'testPassword123'});
 const token=login.cookie;
 const created=await call('/api/events','POST',{title:'Live and Awards',date:'2026-11-09',start:'10:00'},token);
 const id=created.body.event.id;
 let view=await call('/api/events/'+id+'/lease','POST',{},token);
 assert.equal(view.status,200);
 const add=(title,revision)=>call('/api/events/'+id+'/programs','POST',{revision,title,type:'speech',duration:600,gap:60,sourceType:'none'},token);
 view=await add('First speech',view.body.event.revision);
 assert.equal(view.status,201);
 const first=view.body.programs[0].id;
 view=await add('Second speech',view.body.event.revision);
 const second=view.body.programs[1].id;
 const live=(pid,action,revision)=>call('/api/events/'+id+'/live','POST',{programId:pid,action,revision},token);
 let result=await live(second,'start',view.body.event.revision);
 assert.equal(result.status,200);
 assert.equal(result.body.programs[1].status,'running');
 assert.equal(result.body.event.status,'live');
 result=await live(first,'start',result.body.event.revision);
 assert.equal(result.status,409,'cannot start another while running');
 let fresh=await call('/api/events/'+id);
 assert.equal(fresh.status,401,'authentication required');
 fresh=await call('/api/events/'+id,'GET',undefined,token);
 result=await live(second,'pause',fresh.body.event.revision);
 assert.equal(result.status,200);assert.equal(result.body.programs[1].status,'paused');
 assert.equal(result.body.programs[1].resumedAt,null);
 result=await live(second,'resume',result.body.event.revision);
 assert.equal(result.status,200);assert.equal(result.body.programs[1].status,'running');
 result=await live(second,'stop',result.body.event.revision);
 assert.equal(result.status,200);assert.equal(result.body.programs[1].status,'stopped');
 assert.equal(result.body.programs[1].elapsedSeconds,0);
 result=await live(first,'start',result.body.event.revision);
 assert.equal(result.status,200);
 result=await live(first,'finish',result.body.event.revision);
 assert.equal(result.status,200);assert.equal(result.body.programs[0].status,'done');
 result=await live(second,'start',result.body.event.revision);
 assert.equal(result.status,200);
 result=await live(second,'finish',result.body.event.revision);
 assert.equal(result.status,200);assert.equal(result.body.event.status,'completed');
 const awards=async(body)=>call('/api/events/'+id+'/awards','POST',body,token);
 result=await awards({revision:result.body.event.revision,category:'Team',awardName:'Performance Star',winnerName:'Recipient A',presenter:'Guest 1'});
 assert.equal(result.status,201);assert.equal(result.body.awards.length,1);
 const awardId=result.body.awards[0].id;
 result=await awards({revision:result.body.event.revision,category:'Team',awardName:'Excellence',winnerName:'Recipient B'});
 assert.equal(result.status,201);assert.equal(result.body.awards.length,2);
 const order=result.body.awards.map(a=>a.id).reverse();
 result=await call('/api/events/'+id+'/awards/reorder','POST',{revision:result.body.event.revision,ids:order},token);
 assert.equal(result.status,200);
 assert.deepEqual(result.body.awards.map(a=>a.id),order);
 result=await call('/api/events/'+id+'/awards/'+awardId,'PATCH',{revision:result.body.event.revision,status:'presented'},token);
 assert.equal(result.status,200);
 assert.equal(result.body.awards.find(a=>a.id===awardId).status,'presented');
 assert.ok(result.body.awards.find(a=>a.id===awardId).presentedAt);
 const cannotMovePresented=await call('/api/events/'+id+'/awards/reorder','POST',
  {revision:result.body.event.revision,ids:result.body.awards.map(a=>a.id).reverse()},token);
 assert.equal(cannotMovePresented.status,409,'presented awards remain fixed in live reorder');

 const disk=JSON.parse(fs.readFileSync(path.join(folder,'data.json'),'utf8'));
 assert.equal(disk.awards.length,2);
 assert.equal(disk.programs.filter(a=>a.status==='done').length,2);
});
